function attachPasswordToggle(input) {
  const wrapper = document.createElement('div');
  wrapper.className = 'relative';
  input.parentNode.insertBefore(wrapper, input);
  wrapper.appendChild(input);
  input.classList.add('pr-10');

  const toggleBtn = document.createElement('button');
  toggleBtn.type = 'button';
  toggleBtn.setAttribute('aria-label', 'Pokaż/ukryj hasło');
  toggleBtn.className =
    'absolute inset-y-0 right-0 flex items-center px-3 text-gray-400 dark:text-gray-500 hover:text-gray-600 dark:hover:text-gray-300';
  toggleBtn.innerHTML = ICON_EYE;
  toggleBtn.addEventListener('click', () => {
    const isPassword = input.type === 'password';
    input.type = isPassword ? 'text' : 'password';
    toggleBtn.innerHTML = isPassword ? ICON_EYE_SLASH : ICON_EYE;
  });
  wrapper.appendChild(toggleBtn);
}
